// Prepares achievement photos for the site.
//
//   node scripts/process-photos.mjs
//
// Reads _inbox/achievements/<slug>/*.{jpg,jpeg,png,webp} (sorted by file name —
// prefix files with 01-, 02-… to set gallery order), and for each photo:
//   - applies the EXIF rotation, then resizes to fit within 1600×1600
//   - re-encodes as JPEG with NO metadata (EXIF, GPS, ICC, XMP all dropped)
//   - writes public/achievements/<slug>/NN.jpg
// Then writes src/content/achievement-photos.generated.ts with each photo's
// size and a tiny blur placeholder for next/image. Alt text lives in
// src/content/achievements.ts, not here.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const inbox = path.join(root, "_inbox", "achievements");
const out = path.join(root, "public", "achievements");
const MAX = 1600;

const photos = {};
for (const slug of (await readdir(inbox, { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const files = (await readdir(path.join(inbox, slug))).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
  if (!files.length) continue;
  await rm(path.join(out, slug), { recursive: true, force: true });
  await mkdir(path.join(out, slug), { recursive: true });

  photos[slug] = [];
  for (const [i, file] of files.entries()) {
    const name = `${String(i + 1).padStart(2, "0")}.jpg`;
    const src = path.join(inbox, slug, file);
    // sharp keeps no metadata unless .withMetadata()/.keepMetadata() is called.
    const info = await sharp(src)
      .rotate()
      .resize(MAX, MAX, { fit: "inside", withoutEnlargement: true })
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(path.join(out, slug, name));
    const blur = await sharp(src).rotate().resize(16, 16, { fit: "inside" }).jpeg({ quality: 50 }).toBuffer();
    photos[slug].push({
      src: `/achievements/${slug}/${name}`,
      width: info.width,
      height: info.height,
      blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
    });
    console.log(`${slug}/${name}  ${info.width}×${info.height}  ${(info.size / 1024).toFixed(0)} KB  ← ${file}`);
  }
}

await writeFile(
  path.join(root, "src", "content", "achievement-photos.generated.ts"),
  `// Generated by scripts/process-photos.mjs — do not edit by hand.\n` +
    `export type PhotoFile = { src: string; width: number; height: number; blurDataURL: string };\n\n` +
    `export const photoFiles: Record<string, PhotoFile[]> = ${JSON.stringify(photos, null, 2)};\n`,
);
